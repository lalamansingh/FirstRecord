/**
 * Regenerate docs/permissions.md from the code's permission catalog and default roles.
 *   npx tsx scripts/gen-permissions-doc.ts
 * Note: roles are editable at runtime (Users & Roles); this documents the DEFAULTS.
 */
import fs from "node:fs";
import { PERMISSIONS, PERMISSION_GROUPS, DEFAULT_ROLES, type Permission, type RoleKey } from "../src/lib/rbac/permissions";

const roles = Object.keys(DEFAULT_ROLES) as RoleKey[];
const lines: string[] = [];
lines.push("# Roles and permissions", "");
lines.push("<!-- GENERATED by scripts/gen-permissions-doc.ts — do not edit by hand. -->", "");
lines.push(
  "FirstRecord denies everything that a role does not explicitly grant. Permissions are enforced on the server in every server action and API route; hiding a button is never the only control.",
  "",
  "This page documents the **default** role definitions seeded on first install. A user with `role.manage` can change them in **Users & Roles**; every change is audited.",
  "",
  "## Default roles", "",
);
for (const r of roles) lines.push(`- **${DEFAULT_ROLES[r].name}** (\`${r}\`) — ${DEFAULT_ROLES[r].description}`);
lines.push("", "## Permission matrix", "", "✓ = granted by default. Blank = denied.", "");
for (const g of PERMISSION_GROUPS) {
  const perms = (Object.keys(PERMISSIONS) as Permission[]).filter((p) => g.prefix.some((x) => p.startsWith(x)));
  lines.push(`### ${g.label}`, "");
  lines.push(`| Permission | Description | ${roles.map((r) => DEFAULT_ROLES[r].name).join(" | ")} |`);
  lines.push(`|---|---|${roles.map(() => ":-:").join("|")}|`);
  for (const p of perms) {
    lines.push(`| \`${p}\` | ${PERMISSIONS[p]} | ${roles.map((r) => ((DEFAULT_ROLES[r].permissions as readonly string[]).includes(p) ? "✓" : "")).join(" | ")} |`);
  }
  lines.push("");
}
lines.push(
  "## Record-level rules", "",
  "Permissions decide *what* a user may do; record-level rules decide *which records*. They are implemented in `src/lib/rbac/access.ts`.", "",
  "- **Cases.** `case.view.all` means every station. `case.view.station` means cases in the user's own station. `case.view.assigned` means cases where the user is the lead, created the case, or has an active support assignment. A user with none of these sees no cases.",
  "- **Inaccessible records return \"not found\"**, not \"forbidden\", so that case IDs cannot be probed.",
  "- **Statements** need `statement.view`. A statement linked to a case also needs access to that case. An intake still in progress (no case yet) is visible to its creator, and to holders of `statement.view` who have station-wide scope in the same station.",
  "- **Tasks** need `task.view`. A user sees tasks assigned to or created by them, tasks on cases they can see, and every station task when they also hold `task.view.station`.",
  "- **Contact details** (phone, address) of complainants, witnesses and other parties are masked unless the user holds `party.view_pii`.",
  "- **System Administrator** has no case, statement or recording access by default. It manages accounts and technical configuration only.",
  "",
);
fs.writeFileSync("docs/permissions.md", lines.join("\n"));
console.log("Wrote docs/permissions.md");
